// Testa o arquivo 34 (presentes do admin) com dados de TESTE:
// só o admin dá, entrega itens/moedas/ajudas/bolas/pedras, não repete item, o jogador vê só os seus e marca como visto.
// Uso (na pasta ferramentas, uma vez: npm i @electric-sql/pglite@0.3.15):  node testar_presentes.mjs ..
import { PGlite } from "@electric-sql/pglite";
import { citext } from "@electric-sql/pglite/contrib/citext";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";
import fs from "fs"; import path from "path";
const root = process.argv[2];
const db = new PGlite({ extensions: { citext, pgcrypto } });
await db.exec(fs.readFileSync(path.join(root, "ferramentas/supabase_simulado.sql"), "utf8"));
for (const f of fs.readdirSync(path.join(root, "sql")).filter(f => f.endsWith(".sql") && f !== "14_recomecar_do_zero.sql").sort()) await db.exec(fs.readFileSync(path.join(root, "sql", f), "utf8"));
let ok = 0, fail = 0;
const check = (n, c, x = "") => { if (c) { ok++; console.log("  OK  ", n); } else { fail++; console.log("  FALHOU", n, x); } };
const sys = async (q, p = []) => (await db.query(q, p)).rows;
const as = async (uid, q, p = []) => { await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${uid}', false);`); try { return { rows: (await db.query(q, p)).rows }; } catch (e) { return { error: e.message }; } finally { await db.exec("reset role;"); } };
const A = "11111111-1111-1111-1111-111111111111", B = "22222222-2222-2222-2222-222222222222", ADM = "99999999-9999-9999-9999-999999999999";
for (const [u, n] of [[A, "ana"], [B, "beto"], [ADM, "chefe"]]) await sys(`insert into auth.users(id, email, raw_user_meta_data) values ($1, $2, $3)`, [u, n + "@t.l", JSON.stringify({ username: n })]);
await sys(`insert into user_roles(user_id, role) values ($1, 'admin') on conflict do nothing`, [ADM]);
for (const [u, n] of [[A, "Ana"], [B, "Beto"], [ADM, "Chefe"]]) await as(u, `select public.create_character($1, 'mago')`, [n]);
const me = async u => (await sys(`select coins, hints, retries, owned_items from characters where user_id = $1`, [u]))[0];
const gift = (who, args) => as(who, `select * from public.admin_gift($1, $2, $3, $4, $5, $6, $7)`, args);
const item = (await sys(`select id from shop_items where slot = 'chapeu' order by price desc limit 1`))[0].id;
const before = await me(A);
console.log("\nSó o admin");
check("jogador comum não dá presente", /administrador/.test((await gift(B, [A, "oi", [item], 100, 0, 0, "{}"])).error || ""));
console.log("\nEntrega");
const r = await gift(ADM, [A, "Parabéns!", [item, "vila_bandeira_tricolor"], 250, 2, 1, JSON.stringify({ great_ball: 5, pedra_fogo: 1, pedra_sol: 1 })]);
check("presente enviado", !r.error, r.error);
const after = await me(A);
check("moedas, dicas e tente outra vez chegaram", after.coins === before.coins + 250 && after.hints === before.hints + 2 && after.retries === before.retries + 1, JSON.stringify(after));
check("itens chegaram (chapéu e bandeira)", after.owned_items.includes(item) && after.owned_items.includes("vila_bandeira_tricolor"));
const bag = Object.fromEntries((await sys(`select item, qty from bag_items where user_id = $1`, [A])).map(x => [x.item, x.qty]));
check("bolas e pedras na bolsa (inclusive pedra da 2ª)", bag.great_ball === 5 && bag.pedra_fogo === 1 && bag.pedra_sol === 1, JSON.stringify(bag));
console.log("\nRegras");
const r2 = await gift(ADM, [A, "", [item], 0, 0, 0, "{}"]);
check("item que já tem não vem de novo (e sem outro presente, recusa)", /pelo menos um/.test(r2.error || ""), r2.error);
const r3 = await gift(ADM, [A, "", [item], 10, 0, 0, "{}"]);
check("item repetido é ignorado, o resto vai", !r3.error && r3.rows[0].items.length === 0 && r3.rows[0].coins === 10, r3.error);
check("bola inválida recusa", /inválida/.test((await gift(ADM, [A, "", [], 0, 0, 0, JSON.stringify({ master_ball: 1 })])).error || ""));
check("moedas negativas recusam", /de 0 a/.test((await gift(ADM, [A, "", [], -5, 0, 0, "{}"])).error || ""));
check("jogador sem herói recusa", /herói/.test((await gift(ADM, ["33333333-3333-3333-3333-333333333333", "", [], 5, 0, 0, "{}"])).error || ""));
console.log("\nJanela do jogador");
const seenA = (await as(A, `select count(*)::int n from gifts where not seen`)).rows[0].n;
check("Ana vê os presentes dela", seenA === 2, seenA);
check("Beto não vê os presentes da Ana", (await as(B, `select count(*)::int n from gifts`)).rows[0].n === 0);
await as(A, `select public.gifts_seen()`);
check("depois de ver, não aparece de novo", (await as(A, `select count(*)::int n from gifts where not seen`)).rows[0].n === 0);
check("admin vê a lista de todos", (await as(ADM, `select count(*)::int n from gifts`)).rows[0].n === 2);
check("fica na Auditoria", (await sys(`select count(*)::int n from admin_audit_log where action = 'presente'`))[0].n === 2);
check("não entra no Caixa da Obra", (await sys(`select count(*)::int n from donations`))[0].n === 0);
console.log(`\n${ok} testes passaram, ${fail} falharam.`);
process.exit(fail ? 1 : 0);
