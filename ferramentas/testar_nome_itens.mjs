// Testa o arquivo 35 (admin muda o nome dos itens + bandeira verde e branca) com dados de TESTE.
// Uso (na pasta ferramentas, uma vez: npm i @electric-sql/pglite@0.3.15):  node testar_nome_itens.mjs ..
import { PGlite } from "@electric-sql/pglite";
import { citext } from "@electric-sql/pglite/contrib/citext";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";
import fs from "fs"; import path from "path";
const root = process.argv[2];
const db = new PGlite({ extensions: { citext, pgcrypto } });
await db.exec(fs.readFileSync(path.join(root, "ferramentas/supabase_simulado.sql"), "utf8"));
for (const f of fs.readdirSync(path.join(root, "sql")).filter(f => f.endsWith(".sql") && f !== "14_recomecar_do_zero.sql").sort()) await db.exec(fs.readFileSync(path.join(root, "sql", f), "utf8"));
let ok = 0, fail = 0;
const check = (n, c, x = "") => { if (c) { ok++; console.log("  OK  ", n); } else { fail++; console.log("  FALHOU", n, x); } };
const sys = async (q, p = []) => (await db.query(q, p)).rows;
const as = async (uid, q, p = []) => { await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${uid}', false);`); try { return { rows: (await db.query(q, p)).rows }; } catch (e) { return { error: e.message }; } finally { await db.exec("reset role;"); } };
const A = "11111111-1111-1111-1111-111111111111", ADM = "99999999-9999-9999-9999-999999999999";
for (const [u, n] of [[A, "ana"], [ADM, "chefe"]]) await sys(`insert into auth.users(id, email, raw_user_meta_data) values ($1, $2, $3)`, [u, n + "@t.l", JSON.stringify({ username: n })]);
await sys(`insert into user_roles(user_id, role) values ($1, 'admin') on conflict do nothing`, [ADM]);
for (const [u, n] of [[A, "Ana"], [ADM, "Chefe"]]) await as(u, `select public.create_character($1, 'mago')`, [n]);
const ID = "vila_bandeira_verde";
console.log("\nBandeira verde e branca");
const it = (await as(A, `select * from shop_items where id = $1`, [ID])).rows[0];
check("está na loja por 500 moedas", it?.slot === "vila_bandeira" && it.price === 500 && it.name === "Bandeira Verde MG");
check("desenho com 65 linhas de 48 pixels", it?.data.rows.length === 65 && it.data.rows.every(r => r.length === 48));
await sys(`update characters set coins = 600 where user_id = $1`, [A]);
const b = await as(A, `select outfit from public.buy_item($1)`, [ID]);
check("jogador compra e hasteia", !b.error && b.rows[0].outfit.vila_bandeira === ID, b.error);
console.log("\nNome dos itens");
check("jogador comum não muda nome", /administrador/.test((await as(A, `select public.admin_set_item_name($1, 'Hackeada')`, [ID])).error || ""));
const r = await as(ADM, `select name from public.admin_set_item_name($1, '  Bandeira do Verdão Mineiro ')`, [ID]);
check("admin muda o nome (tira espaços das pontas)", r.rows?.[0].name === "Bandeira do Verdão Mineiro", r.error);
check("quem já tem continua com o item", (await sys(`select $1 = any(owned_items) ok from characters where user_id = $2`, [ID, A]))[0].ok);
check("nome muito curto recusa", /2 a 60/.test((await as(ADM, `select public.admin_set_item_name($1, 'x')`, [ID])).error || ""));
check("nome muito longo recusa", /2 a 60/.test((await as(ADM, `select public.admin_set_item_name($1, $2)`, [ID, "a".repeat(61)])).error || ""));
check("item inexistente recusa", /inexistente/.test((await as(ADM, `select public.admin_set_item_name('nao_existe', 'Teste')`)).error || ""));
check("fica na Auditoria", (await sys(`select count(*)::int n from admin_audit_log where action = 'nome_item'`))[0].n === 1);
console.log(`\n${ok} testes passaram, ${fail} falharam.`);
process.exit(fail ? 1 : 0);
