// Testa o arquivo 40 (estagiários do SAC) com dados de TESTE:
// Chupika já cadastrado, admin cria/edita/desativa/apaga, foto conferida, plantão divide os atendimentos,
// resposta automática e do admin com o estagiário certo, jogador vê só os ativos.
// Uso (na pasta ferramentas, uma vez: npm i @electric-sql/pglite@0.3.15):  node testar_sac_estagiarios.mjs ..
import { PGlite } from "@electric-sql/pglite";
import { citext } from "@electric-sql/pglite/contrib/citext";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";
import fs from "fs"; import path from "path";
const root = process.argv[2];
const db = new PGlite({ extensions: { citext, pgcrypto } });
await db.exec(fs.readFileSync(path.join(root, "ferramentas/supabase_simulado.sql"), "utf8"));
for (const f of fs.readdirSync(path.join(root, "sql")).filter(f => f.endsWith(".sql") && f !== "14_recomecar_do_zero.sql").sort()) await db.exec(fs.readFileSync(path.join(root, "sql", f), "utf8"));
let ok = 0, fail = 0;
const check = (n, c, x = "") => { if (c) { ok++; console.log("  OK  ", n); } else { fail++; console.log("  FALHOU", n, x); } };
const sys = async (q, p = []) => (await db.query(q, p)).rows;
const as = async (uid, q, p = []) => { await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${uid}', false);`); try { return { rows: (await db.query(q, p)).rows }; } catch (e) { return { error: e.message }; } finally { await db.exec("reset role;"); } };
const A = "11111111-1111-1111-1111-111111111111", B = "22222222-2222-2222-2222-222222222222", ADM = "99999999-9999-9999-9999-999999999999";
for (const [u, n] of [[A, "ana"], [B, "beto"], [ADM, "chefe"]]) await sys(`insert into auth.users(id, email, raw_user_meta_data) values ($1, $2, $3)`, [u, n + "@t.l", JSON.stringify({ username: n })]);
await sys(`insert into user_roles(user_id, role) values ($1, 'admin') on conflict do nothing`, [ADM]);
for (const [u, n] of [[A, "Ana"], [B, "Beto"], [ADM, "Chefe"]]) await as(u, `select public.create_character($1, 'mago')`, [n]);
const wait = () => sys(`update sac_messages set created_at = created_at - interval '10 seconds'`);
const save = (who, ...a) => as(who, `select * from public.admin_sac_agent_save($1, $2, $3, $4, $5)`, a);
const PHOTO = "data:image/jpeg;base64,/9j/4AAQSkZJRgABAQAAAQABAAD";
console.log("\nCadastro");
const chu = (await as(A, `select * from sac_agents`)).rows;
check("Chupika já vem cadastrado, sem foto", chu.length === 1 && chu[0].name === "Chupika" && !chu[0].photo);
check("jogador comum não cadastra", /administrador/.test((await save(A, null, "Zé", "Estagiário", null, true)).error || ""));
const z = await save(ADM, null, "Zezinho", "Estagiário de Batalhas", PHOTO, true);
check("admin cria estagiário com foto", !z.error && z.rows[0].photo === PHOTO, z.error);
const ZID = z.rows?.[0]?.id;
check("foto que não é imagem recusa", /Foto inválida/.test((await save(ADM, null, "Malvado", "", "javascript:alert(1)", true)).error || ""));
check("nome curto recusa", /2 a 40/.test((await save(ADM, null, "Z", "", null, true)).error || ""));
const e = await save(ADM, ZID, "Zezinho", "Estagiário Chefe", null, true);
check("editar sem mandar foto mantém a foto", e.rows?.[0].photo === PHOTO && e.rows[0].role === "Estagiário Chefe");
console.log("\nPlantão");
const t1 = (await as(A, `select * from public.sac_open('duvida', 'Primeira dúvida aqui')`)).rows[0];
await wait();
const t2 = (await as(B, `select * from public.sac_open('pedido', 'Um pedido aqui')`)).rows[0];
check("os atendimentos se dividem entre os estagiários", t1.agent_id !== t2.agent_id, `${t1.agent_id} ${t2.agent_id}`);
const auto = (await as(B, `select body, agent_id from sac_messages where ticket_id = $1 and auto`, [t2.id])).rows[0];
const agName = (await sys(`select name from sac_agents where id = $1`, [t2.agent_id]))[0].name;
check("a resposta automática usa o nome do estagiário de plantão", auto.body.includes(agName) && auto.agent_id === t2.agent_id, auto.body);
await as(ADM, `select public.sac_reply($1, 'Pode deixar!')`, [t2.id]);
check("resposta do admin sai com o estagiário do atendimento", (await sys(`select agent_id from sac_messages where ticket_id = $1 and not auto and from_admin`, [t2.id]))[0].agent_id === t2.agent_id);
await as(ADM, `select public.admin_sac_assign($1, $2)`, [t1.id, ZID]);
check("admin passa o atendimento para outro estagiário", (await sys(`select agent_id from sac_tickets where id = $1`, [t1.id]))[0].agent_id === ZID);
console.log("\nDesativar e apagar");
await save(ADM, ZID, "Zezinho", "Estagiário Chefe", null, false);
check("jogador não vê estagiário desativado", (await as(A, `select count(*)::int n from sac_agents`)).rows[0].n === 1);
check("admin vê todos", (await as(ADM, `select count(*)::int n from sac_agents`)).rows[0].n === 2);
await wait();
const t3 = (await as(A, `select * from public.sac_open('problema', 'Outro problema aqui')`)).rows[0];
check("desativado não recebe atendimento novo", t3.agent_id !== ZID);
const cid = (await sys(`select id from sac_agents where name = 'Chupika'`))[0].id;
check("não deixa ficar sem nenhum ativo", /pelo menos 1/.test((await save(ADM, cid, "Chupika", "", null, false)).error || ""));
await as(ADM, `select public.admin_sac_agent_delete($1)`, [ZID]);
check("apagar passa os atendimentos para outro", (await sys(`select count(*)::int n from sac_tickets where agent_id is null or agent_id = $1`, [ZID]))[0].n === 0);
check("não apaga o último ativo", /pelo menos 1/.test((await as(ADM, `select public.admin_sac_agent_delete($1)`, [cid])).error || ""));
console.log(`\n${ok} testes passaram, ${fail} falharam.`);
process.exit(fail ? 1 : 0);
