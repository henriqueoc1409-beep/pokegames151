// Testa o arquivo 39 (SAC com o Chupika) com dados de TESTE, como jogadores comuns:
// abrir atendimento, resposta automática, cada um vê só os seus, admin responde, lidos, limites, encerrar.
// Uso (na pasta ferramentas, uma vez: npm i @electric-sql/pglite@0.3.15):  node testar_sac.mjs ..
import { PGlite } from "@electric-sql/pglite";
import { citext } from "@electric-sql/pglite/contrib/citext";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";
import fs from "fs"; import path from "path";
const root = process.argv[2];
const db = new PGlite({ extensions: { citext, pgcrypto } });
await db.exec(fs.readFileSync(path.join(root, "ferramentas/supabase_simulado.sql"), "utf8"));
for (const f of fs.readdirSync(path.join(root, "sql")).filter(f => f.endsWith(".sql") && f !== "14_recomecar_do_zero.sql").sort()) await db.exec(fs.readFileSync(path.join(root, "sql", f), "utf8"));
let ok = 0, fail = 0;
const check = (n, c, x = "") => { if (c) { ok++; console.log("  OK  ", n); } else { fail++; console.log("  FALHOU", n, x); } };
const sys = async (q, p = []) => (await db.query(q, p)).rows;
const as = async (uid, q, p = []) => { await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${uid}', false);`); try { return { rows: (await db.query(q, p)).rows }; } catch (e) { return { error: e.message }; } finally { await db.exec("reset role;"); } };
const A = "11111111-1111-1111-1111-111111111111", B = "22222222-2222-2222-2222-222222222222", ADM = "99999999-9999-9999-9999-999999999999";
for (const [u, n] of [[A, "ana"], [B, "beto"], [ADM, "chefe"]]) await sys(`insert into auth.users(id, email, raw_user_meta_data) values ($1, $2, $3)`, [u, n + "@t.l", JSON.stringify({ username: n })]);
await sys(`insert into user_roles(user_id, role) values ($1, 'admin') on conflict do nothing`, [ADM]);
for (const [u, n] of [[A, "Ana"], [B, "Beto"], [ADM, "Chefe"]]) await as(u, `select public.create_character($1, 'mago')`, [n]);
const wait = () => sys(`update sac_messages set created_at = created_at - interval '10 seconds'`);
console.log("\nAbrir");
check("tipo inválido recusa", /tipo/.test((await as(A, `select public.sac_open('xingar', 'oi tudo bem')`)).error || ""));
check("mensagem curta recusa", /3 a 1000/.test((await as(A, `select public.sac_open('duvida', 'oi')`)).error || ""));
const t = await as(A, `select * from public.sac_open('duvida', 'Como funciona a Liga?')`);
check("Ana abre um atendimento", !t.error && t.rows[0].status === "aberto", t.error);
const T = t.rows?.[0]?.id;
const msgs = (await as(A, `select from_admin, auto, body from sac_messages where ticket_id = $1 order by id`, [T])).rows;
check("Chupika responde sozinho na hora", msgs.length === 2 && msgs[1].auto && msgs[1].from_admin && msgs[1].body.includes("Chupika"));
check("a resposta automática não conta como não lida", (await as(A, `select (last_at > user_seen) n from sac_tickets where id = $1`, [T])).rows[0].n === false);
console.log("\nPrivacidade");
check("Beto não vê o atendimento da Ana", (await as(B, `select count(*)::int n from sac_tickets`)).rows[0].n === 0 && (await as(B, `select count(*)::int n from sac_messages`)).rows[0].n === 0);
check("Beto não responde no atendimento da Ana", /não encontrado/.test((await as(B, `select public.sac_reply($1, 'oi')`, [T])).error || ""));
check("admin vê tudo", (await as(ADM, `select count(*)::int n from sac_messages`)).rows[0].n === 2);
check("ninguém escreve direto na tabela", !!(await as(A, `insert into sac_messages(ticket_id, body) values ($1, 'x')`, [T])).error);
console.log("\nConversa");
check("mensagem rápida demais recusa", /segundos/.test((await as(A, `select public.sac_reply($1, 'mais uma coisa')`, [T])).error || ""));
await wait();
check("Ana manda outra mensagem", !(await as(A, `select public.sac_reply($1, 'E quando começa?')`, [T])).error);
const adm = await as(ADM, `select public.sac_reply($1, 'Começa quando todos chegarem ao Castelo!')`, [T]);
check("admin responde", !adm.error, adm.error);
const tk = (await as(A, `select * from sac_tickets where id = $1`, [T])).rows[0];
check("vira 'respondido' e aparece como não lido para a Ana", tk.status === "respondido" && tk.last_admin && new Date(tk.last_at) > new Date(tk.user_seen));
const last = (await as(A, `select from_admin, auto from sac_messages where ticket_id = $1 order by id desc limit 1`, [T])).rows[0];
check("resposta do admin marcada como do Chupika (não automática)", last.from_admin && !last.auto);
await as(A, `select public.sac_seen($1)`, [T]);
const tk2 = (await as(A, `select * from sac_tickets where id = $1`, [T])).rows[0];
check("Ana leu: some o não lido", new Date(tk2.last_at) <= new Date(tk2.user_seen));
await wait();
await as(A, `select public.sac_reply($1, 'Valeu!')`, [T]);
check("quando a Ana responde, volta a 'aberto' para o admin", (await as(ADM, `select status, last_admin from sac_tickets where id = $1`, [T])).rows[0].status === "aberto");
console.log("\nLimites e encerrar");
for (const k of ["pedido", "problema"]) { await wait(); await as(A, `select public.sac_open($1, 'Mensagem de teste aqui')`, [k]); }
await wait();
check("até 3 atendimentos abertos", /3 atendimentos/.test((await as(A, `select public.sac_open('informacao', 'Mais uma mensagem')`)).error || ""));
check("Beto não encerra o da Ana", /não encontrado/.test((await as(B, `select public.sac_close($1)`, [T])).error || ""));
await as(ADM, `select public.sac_close($1)`, [T]);
check("admin encerra", (await sys(`select status from sac_tickets where id = $1`, [T]))[0].status === "fechado");
await wait();
check("encerrado libera abrir outro", !(await as(A, `select public.sac_open('informacao', 'Mais uma mensagem')`)).error);
console.log(`\n${ok} testes passaram, ${fail} falharam.`);
process.exit(fail ? 1 : 0);
