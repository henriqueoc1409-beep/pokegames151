// Testa o arquivo 44 (Invasão da Equipe Rocket, formato Raid) com dados de TESTE, como jogadores comuns:
// começa no horário, barra coletiva, ceder 1 Pokémon, luta turno a turno, dano conta na barra,
// vitória paga os participantes, derrota sorteia e rouba 1 Pokémon cedido.
// Uso (na pasta ferramentas, uma vez: npm i @electric-sql/pglite@0.3.15):  node testar_rocket.mjs ..
import { PGlite } from "@electric-sql/pglite";
import { citext } from "@electric-sql/pglite/contrib/citext";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";
import fs from "fs"; import path from "path";
const root = process.argv[2];
const db = new PGlite({ extensions: { citext, pgcrypto } });
await db.exec(fs.readFileSync(path.join(root, "ferramentas/supabase_simulado.sql"), "utf8"));
for (const f of fs.readdirSync(path.join(root, "sql")).filter(f => f.endsWith(".sql") && f !== "14_recomecar_do_zero.sql").sort()) await db.exec(fs.readFileSync(path.join(root, "sql", f), "utf8"));
let ok = 0, fail = 0;
const check = (n, c, x = "") => { if (c) { ok++; console.log("  OK  ", n); } else { fail++; console.log("  FALHOU", n, x); } };
const sys = async (q, p = []) => (await db.query(q, p)).rows;
const as = async (uid, q, p = []) => { await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${uid}', false);`); try { return { rows: (await db.query(q, p)).rows }; } catch (e) { return { error: e.message }; } finally { await db.exec("reset role;"); } };
const U = n => `${n}${n}${n}${n}${n}${n}${n}${n}-${n}${n}${n}${n}-${n}${n}${n}${n}-${n}${n}${n}${n}-${String(n).repeat(12)}`;
const [A, B, C, D, ADM] = [U(1), U(2), U(3), U(4), U(9)];
for (const [u, n] of [[A, "ana"], [B, "beto"], [C, "caio"], [D, "duda"], [ADM, "chefe"]]) await sys(`insert into auth.users(id, email, raw_user_meta_data) values ($1, $2, $3)`, [u, n + "@t.l", JSON.stringify({ username: n })]);
await sys(`insert into user_roles(user_id, role) values ($1, 'admin') on conflict do nothing`, [ADM]);
for (const [u, n] of [[A, "Ana"], [B, "Beto"], [C, "Caio"], [D, "Duda"], [ADM, "Chefe"]]) await as(u, `select public.create_character($1, 'mago')`, [n]);
const mon = async (u, sp, lv, slot) => { const id = (await sys(`select (public.pk_new_monster($1, $2, $3)).id`, [u, sp, lv]))[0].id; if (slot) await sys(`update monsters set team_slot = $2 where id = $1`, [id, slot]); return id; };
const MA = await mon(A, 6, 40, 1), MA2 = await mon(A, 3, 40, 2), MB = await mon(B, 9, 40, 1), MC = await mon(C, 25, 30, 1);
const cur = async u => (await as(u, `select public.rocket_current() r`)).rows?.[0]?.r;
console.log("\nComeça no horário");
await sys(`update game_config set config = jsonb_set(config, '{rocket,days}', '[0,1,2,3,4,5,6]') where active`);
await sys(`update game_config set config = jsonb_set(config, '{rocket,hour}', '25') where active`);
check("antes do horário, nada", (await cur(A)) === null);
await sys(`update game_config set config = jsonb_set(config, '{rocket,hour}', '0') where active`);
let r = await cur(A);
check("no dia e na hora, a Rocket invade sozinha", r?.status === "ativa" && r.team.length === 3, JSON.stringify(r)?.slice(0, 200));
check("barra coletiva conforme os jogadores com Pokémon (3)", r.players === 3 && r.hp_total > 0 && r.hp_left === r.hp_total, JSON.stringify({ p: r.players, hp: r.hp_total }));
check("aparece no Jornal", (await sys(`select count(*)::int n from event_log where kind = 'rocket'`))[0].n === 1);
check("só uma invasão por vez", (await cur(B)).id === r.id && (await sys(`select count(*)::int n from rocket_raids`))[0].n === 1);
check("admin não chama outra com uma ativa", /já está invadindo/.test((await as(ADM, `select public.admin_rocket_start(24)`)).error || ""));
console.log("\nCeder e lutar");
check("não cede Pokémon de outro", /Pokémon seu/.test((await as(A, `select public.rocket_join($1)`, [MB])).error || ""));
const bidA = (await as(A, `select public.rocket_join($1) b`, [MA])).rows?.[0]?.b;
check("Ana cede o Charizard e a luta começa", !!bidA);
check("só 1 Pokémon por invasão", /já cedeu/.test((await as(A, `select public.rocket_join($1)`, [MA2])).error || ""));
const bt = (await as(A, `select * from battles where id = $1`, [bidA])).rows[0];
check("luta 1 contra os 3 da Rocket", bt.mode === "rocket" && bt.state.sides[0].mons.length === 1 && bt.state.sides[1].mons.length === 3 && bt.state.sides[1].name === "Equipe Rocket");
let t = bt.turn, guard = 0, hp0 = (await cur(A)).hp_left;
const act = async (u, id) => { const b = (await as(u, `select * from battles where id = $1`, [id])).rows[0]; if (b.status !== "ativa") return b;
  const mv = b.state.sides[0].mons[0].moves.findIndex(m => m.pp > 0); return (await as(u, `select * from public.battle_act($1, $2, 'move', $3)`, [id, b.turn, mv < 0 ? -1 : mv])).rows?.[0] || { error: 1 }; };
let b1 = await act(A, bidA);
check("cada turno: o servidor joga pela Rocket na hora", !b1.error && b1.turn > t, JSON.stringify(b1).slice(0, 160));
const hp1 = (await cur(A)).hp_left;
check("o dano sai da barra coletiva", hp1 < hp0 && (await cur(B)).ranking[0].damage === hp0 - hp1, `${hp0} -> ${hp1}`);
while (b1.status === "ativa" && guard++ < 60) b1 = await act(A, bidA);
check("a luta termina (desmaio, Rocket derrotada ou fuga)", b1.status === "encerrada");
check("a parte da Ana fica como feita", (await cur(A)).me.done === true);
check("a batalha não vai para a Arena", (await sys(`select count(*)::int n from arena_battles`))[0].n === 0);
console.log("\nVitória");
const bidB = (await as(B, `select public.rocket_join($1) b`, [MB])).rows[0].b;
await sys(`update rocket_raids set hp_left = 1 where id = $1`, [r.id]);
const cB0 = (await sys(`select coins from characters where user_id = $1`, [B]))[0].coins, cA0 = (await sys(`select coins from characters where user_id = $1`, [A]))[0].coins, cD0 = (await sys(`select coins from characters where user_id = $1`, [D]))[0].coins;
await act(B, bidB);
r = await cur(B);
check("barra zerada: vitória", r.status === "vitoria" && r.hp_left === 0, r.status);
check("participantes ganham 100 moedas (Ana e Beto)", (await sys(`select coins from characters where user_id = $1`, [A]))[0].coins === cA0 + 100 && (await sys(`select coins from characters where user_id = $1`, [B]))[0].coins >= cB0 + 100);
check("quem não participou não ganha", (await sys(`select coins from characters where user_id = $1`, [D]))[0].coins === cD0);
check("depois da vitória ninguém mais entra", /não está invadindo/.test((await as(C, `select public.rocket_join($1)`, [MC])).error || ""));
console.log("\nDerrota e roubo");
await sys(`update rocket_raids set starts_at = starts_at - interval '3 days', ends_at = ends_at - interval '3 days'`);
await sys(`update game_config set config = jsonb_set(config, '{rocket,days}', '[]') where active`);
r = (await as(ADM, `select * from public.admin_rocket_start(2)`)).rows?.[0];
check("admin chama a Rocket na hora", r?.status === "ativa");
await as(A, `select public.rocket_join($1)`, [MA2]); await as(C, `select public.rocket_join($1)`, [MC]);
const before = (await sys(`select count(*)::int n from monsters`))[0].n;
await sys(`update rocket_raids set ends_at = now() - interval '1 minute' where id = $1`, [r.id]);
r = await cur(D);
check("tempo acabou com vida sobrando: derrota", r.status === "derrota", r.status);
check("o sorteado é um participante", [A, C].includes(r.stolen_user), r.stolen_user);
check("só 1 Pokémon foi roubado, e é o que ele cedeu", (await sys(`select count(*)::int n from monsters`))[0].n === before - 1 && (await sys(`select count(*)::int n from monsters where id = any($1)`, [[MA2, MC]]))[0].n === 1);
check("os outros Pokémon do sorteado continuam", (await sys(`select count(*)::int n from monsters where id = $1`, [MA]))[0].n === 1);
check("aparece no Jornal quem perdeu o quê", (await sys(`select count(*)::int n from event_log where kind = 'rocket' and message like '%roubou%'`))[0].n === 1);
check("Duda (não participou) não perdeu nada", (await sys(`select count(*)::int n from monsters where user_id = $1`, [D]))[0].n === 0 && r.stolen_user !== D);
console.log("\nSem participantes");
const r3 = (await as(ADM, `select * from public.admin_rocket_start(1)`)).rows?.[0];
await sys(`update rocket_raids set ends_at = now() - interval '1 minute' where id = $1`, [r3.id]);
const f3 = await cur(A);
check("ninguém cedeu: a Rocket vai embora sem levar nada", f3.status === "derrota" && !f3.stolen_user);
check("jogador comum não chama a Rocket", /administrador/.test((await as(A, `select public.admin_rocket_start(24)`)).error || ""));
check("ninguém escreve direto nas tabelas", !!(await as(A, `update rocket_raids set hp_left = 0`)).error);
console.log(`\n${ok} testes passaram, ${fail} falharam.`);
process.exit(fail ? 1 : 0);
