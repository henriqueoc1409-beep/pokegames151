// Testa o arquivo 41 (Jornal permanente) com dados de TESTE:
// "apagar" agora arquiva, nada some, todos veem os arquivados, admin desarquiva; imagens não vencem mais.
// Uso (na pasta ferramentas, uma vez: npm i @electric-sql/pglite@0.3.15):  node testar_jornal_permanente.mjs ..
import { PGlite } from "@electric-sql/pglite";
import { citext } from "@electric-sql/pglite/contrib/citext";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";
import fs from "fs"; import path from "path";
const root = process.argv[2];
const db = new PGlite({ extensions: { citext, pgcrypto } });
await db.exec(fs.readFileSync(path.join(root, "ferramentas/supabase_simulado.sql"), "utf8"));
for (const f of fs.readdirSync(path.join(root, "sql")).filter(f => f.endsWith(".sql") && f !== "14_recomecar_do_zero.sql").sort()) await db.exec(fs.readFileSync(path.join(root, "sql", f), "utf8"));
let ok = 0, fail = 0;
const check = (n, c, x = "") => { if (c) { ok++; console.log("  OK  ", n); } else { fail++; console.log("  FALHOU", n, x); } };
const sys = async (q, p = []) => (await db.query(q, p)).rows;
const as = async (uid, q, p = []) => { await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${uid}', false);`); try { return { rows: (await db.query(q, p)).rows }; } catch (e) { return { error: e.message }; } finally { await db.exec("reset role;"); } };
const A = "11111111-1111-1111-1111-111111111111", ADM = "99999999-9999-9999-9999-999999999999";
for (const [u, n] of [[A, "ana"], [ADM, "chefe"]]) await sys(`insert into auth.users(id, email, raw_user_meta_data) values ($1, $2, $3)`, [u, n + "@t.l", JSON.stringify({ username: n })]);
await sys(`insert into user_roles(user_id, role) values ($1, 'admin') on conflict do nothing`, [ADM]);
for (const [u, n] of [[A, "Ana"], [ADM, "Chefe"]]) await as(u, `select public.create_character($1, 'mago')`, [n]);
const p = await as(ADM, `select * from public.admin_save_post(null, 'aviso', 'Aviso importante', 'Texto', '{}', null, true)`);
check("admin publica aviso fixado", !p.error && p.rows[0].pinned, p.error);
const ID = p.rows?.[0]?.id;
console.log("\nArquivar em vez de apagar");
await as(ADM, `select public.admin_delete_post($1)`, [ID]);
const a = (await as(A, `select * from posts where id = $1`, [ID])).rows[0];
check("'apagar' só arquiva: o aviso continua no Jornal", !!a && a.archived && !a.pinned);
check("jogador vê o arquivado", (await as(A, `select count(*)::int n from posts`)).rows[0].n === 1);
check("jogador comum não arquiva", /administrador/.test((await as(A, `select public.admin_archive_post($1, false)`, [ID])).error || ""));
await as(ADM, `select public.admin_archive_post($1, false)`, [ID]);
check("admin tira do arquivo", (await sys(`select archived from posts where id = $1`, [ID]))[0].archived === false);
check("vai para a Auditoria", (await sys(`select count(*)::int n from admin_audit_log where action like 'aviso_%arquivado'`))[0].n === 2);
console.log("\nImagens para sempre");
const IMG = "data:image/jpeg;base64,/9j/4AAQSkZJRgABAQAAAQABAAD";
check("admin põe imagem", !(await as(ADM, `select public.admin_post_image($1, $2)`, [ID, IMG])).error);
await sys(`update post_images set created_at = now() - interval '400 days'`);
await sys(`update posts set image_at = now() - interval '400 days' where id = $1`, [ID]);
await as(A, `select public.post_images_purge()`);
check("imagem de mais de 1 ano continua no banco", (await sys(`select count(*)::int n from post_images`))[0].n === 1);
check("e o jogador continua vendo", (await as(A, `select count(*)::int n from post_images`)).rows[0].n === 1);
console.log(`\n${ok} testes passaram, ${fail} falharam.`);
process.exit(fail ? 1 : 0);
